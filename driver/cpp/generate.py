"""The C++ driver: a Solution and an example in, a runnable program out.

    generate(source, example) -> Program(problem, prelude, main)

- `problem` is the trace's problem object (trace-format.md, Section 4).
- `prelude` is a header passed to the compiler with -include: the standard
  headers, `using namespace std;`, our ListNode and TreeNode, and any node
  class from a comment with its Fields table. It is not written into the
  program file, so the user's line numbers do not move.
- `main` is appended after the user's (instrumented) code. It calls begin(),
  builds each argument from the example, calls the method, and writes the
  trace with write_result() or write_void_result().

Build and run:
    clang++ -std=c++20 -I adapters/cpp/runtime -include prelude.hpp program.cpp -o program
    TRACE_OUT=trace.json ./program
"""

import json
import re
from dataclasses import dataclass, field

from .. import shapes
from ..errors import DriverError
from ..example import parse_example
from .nodes import node_types
from .signature import choose_method, read_methods
from .types import clean, declared_type, neutral, parse_neutral

# What LeetCode's C++ environment makes available without an #include. The list
# is ours: <bits/stdc++.h> does not exist in libc++ (macOS), so each header is
# named. LeetCode's own stubs write `vector<int>` with no std::, which is why
# the prelude says `using namespace std;`.
# The standard headers and the runtime: adapters/cpp/runtime/prelude_common.hpp,
# one file shared with the sandbox image, which precompiles it.
COMMON_HEADER = "prelude_common.hpp"

RAW_DELIMITER = "__trace__"


@dataclass
class Program:
    problem: dict
    prelude: str
    main: str
    warnings: list = field(default_factory=list)

    def source(self, user_code):
        """The program file: the user's code first, so its lines keep their numbers, then main."""
        return user_code.rstrip("\n") + "\n\n" + self.main


def generate(source, example, method_name=None):
    types = node_types(source)
    values = parse_example(example)

    def has_list_param(m):
        return any(clean(p.ctype) == "ListNode*" for p in m.params)

    method, mapping = choose_method(read_methods(source), list(values), has_list_param, method_name)
    warnings = []
    if any(e != p for e, p in mapping.items()):
        renamed = ", ".join(f"{e} -> {p}" for e, p in mapping.items() if e != p)
        warnings.append(f"The example's names do not match {method.name}'s parameters, so the values were passed in order ({renamed}).")

    node_names = list(types)
    params = []
    for p in method.params:
        params.append({"name": p.name, "type": neutral(p.ctype, node_names, f"parameter {p.name!r}")})
    returns = neutral(method.return_ctype, node_names, f"the return type of {method.name}")
    for p in params:
        if p["type"] == "void":
            raise DriverError(f"parameter {p['name']!r} cannot have type void.")

    by_param = {mapping[name]: value for name, value in values.items() if name in mapping}
    pos = values.get("pos", -1) if "pos" in values and "pos" not in mapping else -1
    problem = {"method": method.name, "params": params, "returns": {"type": returns},
               "input": {p["name"]: by_param[p["name"]] for p in params}}

    builder = _Builder(types)
    lines = []
    for p, cparam in zip(params, method.params):
        value = by_param[p["name"]]
        lines.append(f"  // {p['name']} = {json.dumps(value, separators=(',', ':'))}"
                     + (f", pos = {pos}" if pos != -1 and p["type"] == "ListNode" else ""))
        statements, expr = builder.build(value, parse_neutral(p["type"]), p["name"], p["name"],
                                         pos if p["type"] == "ListNode" else -1)
        lines += ["  " + s for s in statements]
        lines.append(f"  {declared_type(cparam.ctype)} {p['name']} = {expr};")
        lines.append("")
    if pos != -1 and not any(p["type"] == "ListNode" for p in params):
        raise DriverError("pos is only used with a ListNode parameter.")

    args = ", ".join(p["name"] for p in params)
    problem_json = json.dumps(problem, ensure_ascii=False, separators=(", ", ": "))
    if f"){RAW_DELIMITER}\"" in problem_json:
        raise DriverError("The example contains text the driver cannot embed.")

    call = [f"  Solution solution;"]
    if returns == "void":
        call += [f"  solution.{method.name}({args});", "  ::trace::write_void_result();"]
    else:
        call += [f"  auto answer = solution.{method.name}({args});", "  ::trace::write_result(answer);"]

    main = "\n".join([
        "// ---- Generated by the driver (docs/driver-generation.md). Not part of the user's code. ----",
        "int main() {",
        f'  ::trace::tracer.begin(R"{RAW_DELIMITER}({problem_json}){RAW_DELIMITER}");',
        "",
        *lines,
        *call,
        "  return 0;",
        "}",
        "",
    ])
    return Program(problem, _prelude(types), main, warnings)


def _prelude(types):
    out = [
        "// Generated by the driver (docs/driver-generation.md). Passed to the compiler",
        "// with -include, so it comes before the user's code without adding lines to it.",
        "#pragma once",
        "",
        f'#include "{COMMON_HEADER}"  // the standard headers, ListNode, TreeNode, and trace.hpp',
        "",
        "using namespace std;",
    ]
    for t in types.values():
        if not t.supplied:
            out += ["", f"// {t.name}, from the comment in the user's code.", t.definition, "", t.fields_table()]
    return "\n".join(out) + "\n"


class _Builder:
    """Stage 2 for C++: a neutral value plus its neutral type -> C++ code.

    build() returns (statements, expression). Primitives and arrays need no
    statements: `{1, 2, 3}`. Node structures need statements that create and
    link the nodes, and the expression is the root pointer.
    """

    def __init__(self, types):
        self.types = types
        self.counter = 0

    def build(self, value, ntype, where, prefix, pos=-1):
        kind, args = ntype
        if kind == "int":
            return [], self._int(value, where)
        if kind == "float":
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise DriverError(f"{where} should be a number, found {value!r}.")
            text = repr(float(value))
            return [], text if any(c in text for c in ".e") else text + ".0"
        if kind == "bool":
            if not isinstance(value, bool):
                raise DriverError(f"{where} should be true or false, found {value!r}.")
            return [], "true" if value else "false"
        if kind == "string":
            if not isinstance(value, str):
                raise DriverError(f"{where} should be a string in double quotes, found {value!r}.")
            return [], _cpp_string(value)
        if kind == "char":
            if not isinstance(value, str) or len(value) != 1 or ord(value) > 127:
                raise DriverError(f"{where} should be one character in double quotes, such as \"a\", found {value!r}.")
            return [], _cpp_char(value)
        if kind == "array":
            if not isinstance(value, list):
                raise DriverError(f"{where} should be an array, found {value!r}.")
            statements, items = [], []
            for i, item in enumerate(value):
                s, e = self.build(item, args[0], f"{where}[{i}]", f"{prefix}_{i}")
                statements += s
                items.append(e)
            return statements, "{" + ", ".join(items) + "}"
        if kind in self.types:
            return self._nodes(value, self.types[kind], where, prefix, pos)
        raise DriverError(f"{where}: the driver cannot build an input of type {_spell(ntype)} from an example yet.")

    def _int(self, value, where):
        if isinstance(value, bool) or not isinstance(value, int):
            raise DriverError(f"{where} should be an integer, found {value!r}.")
        if not -(2 ** 63) <= value < 2 ** 63:
            raise DriverError(f"{where} = {value} does not fit in 64 bits.")
        if -(2 ** 31) <= value < 2 ** 31:
            return str(value)
        return f"{value}LL"

    def _nodes(self, value, t, where, prefix, pos):
        shape = t.shape
        if shape == "linked-list":
            decoded = shapes.linked_list(value, where, pos)
        elif shape == "binary-tree":
            decoded = shapes.binary_tree(value, where)
        elif shape == "binary-tree-with-next":
            decoded = shapes.binary_tree(value, where, extra=("next",))
        elif shape == "graph":
            decoded = shapes.graph(value, where)
        elif shape == "random-list":
            decoded = shapes.random_list(value, where)
        elif shape == "nary-tree":
            decoded = shapes.nary_tree(value, where)
        else:
            raise DriverError(f"{where}: the driver does not know how LeetCode writes a {t.name} with fields "
                              f"{t.fields} in an example, so it cannot build it yet.")
        if decoded.root is None:
            return [], "nullptr"

        names = [f"{prefix}_n{i}" for i in range(len(decoded.nodes))]
        out = []
        for name, node in zip(names, decoded.nodes):
            if t.int_constructor:
                out.append(f"{t.name} *{name} = new {t.name}({node['val']});")
            else:
                out += [f"{t.name} *{name} = new {t.name}();", f"{name}->val = {node['val']};"]
        for name, node in zip(names, decoded.nodes):
            for f in t.fields:
                if f == "val":
                    continue
                link = node[f]
                if isinstance(link, list):
                    out.append(f"{name}->{f} = {{{', '.join(names[i] for i in link)}}};")
                else:
                    out.append(f"{name}->{f} = {names[link] if link is not None else 'nullptr'};")
        return out, names[decoded.root]


def _spell(ntype):
    kind, args = ntype
    return kind + (f"<{', '.join(_spell(a) for a in args)}>" if args else "")


def _cpp_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\x{ord(ch):02x}\"\"")  # close and reopen, so the next character is not read as hex
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _cpp_char(ch):
    return {"\\": "'\\\\'", "'": "'\\''", "\n": "'\\n'", "\t": "'\\t'"}.get(ch, f"'{ch}'" if ord(ch) >= 0x20 else f"'\\x{ord(ch):02x}'")
