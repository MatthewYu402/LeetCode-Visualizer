"""The Java driver: a Solution and an example in, the files a Java run needs out.

    generate(source, example) -> Program(problem, main, nodes)

- `problem` is the trace's problem object (trace-format.md, Section 4), written to
  problem.json, which the runtime copies into the trace.
- `main` is LvMain.java: it builds each argument from the example as Java literals (as the
  C++ driver writes them into main), calls the method, and ends the trace with
  Trace.finish(answer), or Trace.failed(t) when the user's code throws.
- `nodes` is Nodes.java: ListNode and TreeNode as LeetCode defines them, and any node class
  from a comment, unless the user's code defines it.

The user's file is compiled as Solution.java, untouched but for the imports LeetCode's Java
environment gives (adapters/java/src/lvtrace/Build.java), so its lines keep their numbers.
"""

import json
from dataclasses import dataclass, field

from .. import shapes
from ..cpp.signature import choose_method
from ..errors import DriverError
from ..example import parse_example
from ..hints import infer_hint
from .nodes import SUPPLIED_SOURCE, node_types
from .signature import read_methods
from .types import FLOATS, INTS, neutral, parse

# Above this many values, an array is written as text the runtime reads (lvtrace.Args), not as
# a literal: javac allows 64 KB of bytecode per method, and a literal of ten thousand ints is more.
LITERAL_LIMIT = 500


@dataclass
class Program:
    problem: dict
    main: str
    nodes: str
    warnings: list = field(default_factory=list)

    def problem_json(self):
        return json.dumps(self.problem, ensure_ascii=False, separators=(", ", ": ")) + "\n"


def generate(source, example, method_name=None):
    types = node_types(source)
    values = parse_example(example)

    def has_list_param(m):
        return any(_base(p.ctype) == "ListNode" for p in m.params)

    method, mapping = choose_method(read_methods(source), list(values), has_list_param, method_name)
    warnings = []
    if any(e != p for e, p in mapping.items()):
        renamed = ", ".join(f"{e} -> {p}" for e, p in mapping.items() if e != p)
        warnings.append(f"The example's names do not match {method.name}'s parameters, so the values were passed in order ({renamed}).")

    names = list(types)
    params = [{"name": p.name, "type": neutral(p.ctype, names, f"parameter {p.name!r}")} for p in method.params]
    returns = neutral(method.return_ctype, names, f"the return type of {method.name}", returns=True)
    by_param = {mapping[name]: value for name, value in values.items() if name in mapping}
    for p in params:
        hint = infer_hint(p["name"], p["type"], by_param.get(p["name"]))
        if hint:
            p["hint"] = hint
    pos = values.get("pos", -1) if "pos" in values and "pos" not in mapping else -1
    if pos != -1 and not any(p["type"] == "ListNode" for p in params):
        raise DriverError("pos is only used with a ListNode parameter.")
    problem = {"method": method.name, "params": params, "returns": {"type": returns},
               "input": {p["name"]: by_param[p["name"]] for p in params}}

    builder = _Builder(types)
    lines = []
    for p, jparam in zip(params, method.params):
        value = by_param[p["name"]]
        lines.append(f"      // {p['name']} = {json.dumps(value, separators=(',', ':'))}"
                     + (f", pos = {pos}" if pos != -1 and p["type"] == "ListNode" else ""))
        statements, expr = builder.build(value, parse(jparam.ctype), p["name"], p["name"],
                                         pos if p["type"] == "ListNode" else -1)
        lines += ["      " + s for s in statements]
        lines.append(f"      {jparam.ctype} {p['name']} = {expr};")
    args = ", ".join(p["name"] for p in params)
    target = "Solution" if getattr(method, "static", False) else "solution"
    call = ([f"      {target}.{method.name}({args});", "      lvtrace.Trace.finishVoid();"] if returns == "void"
            else [f"      Object answer = {target}.{method.name}({args});", "      lvtrace.Trace.finish(answer);"])
    main = "\n".join([
        "// Generated by the driver (docs/driver-generation.md). Not part of the user's code.",
        "public class LvMain {",
        "  public static void main(String[] args) {",
        "    lvtrace.Trace.begin();",
        "    try {",
        *lines,
        "      Solution solution = new Solution();",
        "      lvtrace.Trace.start(solution);",
        *call,
        "    } catch (Throwable t) {",
        "      lvtrace.Trace.failed(t);",
        "    }",
        "  }",
        "}",
        "",
    ])
    nodes = []
    for t in types.values():
        if t.in_code:
            continue
        nodes.append(SUPPLIED_SOURCE[t.name] if t.supplied else t.definition.strip())
    nodes_text = "// Node classes: LeetCode's ListNode and TreeNode, and any from the comment in the user's code.\n" \
                 + "\n".join(nodes) + "\n"
    return Program(problem, main, nodes_text, warnings)


def _base(ctype):
    try:
        t = parse(ctype)
    except ValueError:
        return ""
    return t.base if not t.dims else ""


class _Builder:
    """A neutral value plus its Java type -> Java code: (statements, expression)."""

    def __init__(self, types):
        self.types = types

    def build(self, value, t, where, prefix, pos=-1):
        if t.dims:
            return self._array(value, t, where, prefix)
        b = t.base
        if b in INTS:
            return [], self._int(value, b, where)
        if b in FLOATS:
            return [], self._float(value, b, where)
        if b in ("boolean", "Boolean"):
            if not isinstance(value, bool):
                raise DriverError(f"{where} should be true or false, found {value!r}.")
            return [], "true" if value else "false"
        if b in ("char", "Character"):
            if not isinstance(value, str) or len(value) != 1:
                raise DriverError(f"{where} should be one character in double quotes, such as \"a\", found {value!r}.")
            return [], _char(value)
        if b in ("String", "CharSequence"):
            if not isinstance(value, str):
                raise DriverError(f"{where} should be a string in double quotes, found {value!r}.")
            return [], _string(value)
        if b in ("List", "ArrayList", "Collection", "LinkedList") and len(t.args) == 1:
            if not isinstance(value, list):
                raise DriverError(f"{where} should be an array, found {value!r}.")
            elem = t.args[0]
            cls = "LinkedList" if b == "LinkedList" else "ArrayList"
            if len(value) > LITERAL_LIMIT and elem.base in ("Integer", "Long") and not elem.dims:
                for i, v in enumerate(value):
                    self._int(v, elem.base, f"{where}[{i}]")
                kind = "intList" if elem.base == "Integer" else "longList"
                return [], f"new {cls}<{elem.text}>(lvtrace.Args.{kind}({_string(','.join(map(str, value)))}))"
            statements, items = [], []
            for i, item in enumerate(value):
                s, e = self.build(item, elem, f"{where}[{i}]", f"{prefix}_{i}")
                statements += s
                items.append(e)
            if not items:
                return statements, f"new {cls}<{elem.text}>()"
            return statements, f"new {cls}<{elem.text}>(Arrays.asList({', '.join(items)}))"
        if b in self.types:
            return self._nodes(value, self.types[b], where, prefix, pos)
        raise DriverError(f"{where}: the driver cannot build an input of type {t.text} from an example yet.")

    def _array(self, value, t, where, prefix):
        if not isinstance(value, list):
            raise DriverError(f"{where} should be an array, found {value!r}.")
        elem = t.element()
        statements, items = [], []
        for i, item in enumerate(value):  # built (and so checked) either way, so an error names the value
            s, e = self.build(item, elem, f"{where}[{i}]", f"{prefix}_{i}")
            statements += s
            items.append(e)
        if _count(value) > LITERAL_LIMIT and t.base in ("int", "long", "double", "char", "boolean", "String") and t.dims <= 2:
            text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
            return [], f"lvtrace.Args.{t.base.lower()}{t.dims}({_string(text)})"
        return statements, f"new {_array_type(t)}{{{', '.join(items)}}}"

    def _int(self, value, base, where):
        if isinstance(value, bool) or not isinstance(value, int):
            raise DriverError(f"{where} should be an integer, found {value!r}.")
        bits = {"int": 32, "Integer": 32, "long": 64, "Long": 64, "short": 16, "Short": 16, "byte": 8, "Byte": 8}[base]
        if not -(2 ** (bits - 1)) <= value < 2 ** (bits - 1):
            raise DriverError(f"{where} = {value} does not fit in a Java {base}.")
        if base in ("long", "Long"):
            return f"{value}L"
        if base in ("short", "Short", "byte", "Byte"):
            return f"({base.lower()}) {value}"  # a cast: an int literal is not a short or a Byte where it is boxed
        return str(value)

    def _float(self, value, base, where):
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise DriverError(f"{where} should be a number, found {value!r}.")
        text = repr(float(value))
        if text in ("inf", "-inf", "nan"):
            raise DriverError(f"{where} should be a finite number, found {value!r}.")
        return text + ("f" if base in ("float", "Float") else "")

    def _nodes(self, value, t, where, prefix, pos):
        shape = t.shape
        if shape == "linked-list":
            decoded = shapes.linked_list(value, where, pos)
        elif shape == "binary-tree":
            decoded = shapes.binary_tree(value, where)
        elif shape == "binary-tree-with-next":
            decoded = shapes.binary_tree(value, where, extra=("next",))
        elif shape == "graph":
            decoded = shapes.graph(value, where)
        elif shape == "random-list":
            decoded = shapes.random_list(value, where)
        elif shape == "nary-tree":
            decoded = shapes.nary_tree(value, where)
        else:
            raise DriverError(f"{where}: the driver does not know how LeetCode writes a {t.name} with fields "
                              f"{t.fields} in an example, so it cannot build it yet.")
        if decoded.root is None:
            return [], "null"
        names = [f"{prefix}_n{i}" for i in range(len(decoded.nodes))]
        out = []
        for name, node in zip(names, decoded.nodes):
            if t.no_arg_constructor or not t.int_constructor:
                out += [f"{t.name} {name} = new {t.name}();", f"{name}.val = {node['val']};"]
            else:
                out.append(f"{t.name} {name} = new {t.name}({node['val']});")
        for name, node in zip(names, decoded.nodes):
            for f in t.fields:
                if f == "val":
                    continue
                link = node[f]
                if isinstance(link, list):
                    items = ", ".join(names[i] for i in link)
                    out.append(f"{name}.{f} = new ArrayList<>(Arrays.asList({items}));" if items else f"{name}.{f} = new ArrayList<>();")
                else:
                    out.append(f"{name}.{f} = {names[link] if link is not None else 'null'};")
        return out, names[decoded.root]


def _array_type(t):
    """`new int[][]` for int[][]: the creation expression's type, from the declared one."""
    return f"{t.base}" + ("<" + ", ".join(a.text for a in t.args) + ">" if t.args else "") + "[]" * t.dims


def _count(value):
    return sum(_count(v) for v in value) if isinstance(value, list) else 1


def _string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _char(ch):
    special = {"\\": "'\\\\'", "'": "'\\''", "\n": "'\\n'", "\t": "'\\t'", "\r": "'\\r'"}
    if ch in special:
        return special[ch]
    return f"'\\u{ord(ch):04x}'" if ord(ch) < 0x20 else f"'{ch}'"
